  """The site Hugo builds from web/ and the made-up constitution."""

  def build(
    self,
    lengths: dict[str, object] | None = None,
    raw: bool = False,
    index: str = INDEX,
    design: dict[str, str] = DESIGN,
    rules: bool = True,
    per_page: int | None = None,
    edit_rules: Callable[[Path], None] | None = None,
    other: bool = False,
  ) -> dict[str, str]:
    """Build the site in a temporary copy of the repo's layout.

    Args:
      lengths: The content of web/data/lengths.json, or None for no file.
      raw: Whether to return the pages' HTML instead of their text.
      index: The content of index.toml.
      design: The files of docs/design/ by path.
      rules: Whether to write web/data/rules.json, from the rules of
        site_fixture.
      per_page: The rules a page of their list shows, if not the site's.
      edit_rules: Changes the rules' checkout before site-rules reads it.
      other: Whether site-rules also reads site_fixture's second source,
        `demo`, global private, with a rule set enabling R3 and demo:2.

    Returns:
      The visible text of every page, or its HTML, by path.
    """
    with tempfile.TemporaryDirectory() as tmp:
      root = Path(tmp)
      shutil.copytree(
        ROOT / "web",
        root / "web",
        ignore=shutil.ignore_patterns("themes", "data", "resources"),
      )
      (root / "web/themes").mkdir()
      (root / "web/themes/hugo-book").symlink_to(ROOT / "web/themes/hugo-book")
      sources = root / "constitution/2026-10"
      generated = sources / "generated"
      generated.mkdir(parents=True)
      (sources / "index.toml").write_text(index)
      for name, text in FILES.items():
        (generated / f"constitution.{name}.md").write_text(text)
      for name, text in design.items():
        (root / "docs/design" / name).parent.mkdir(parents=True, exist_ok=True)
        (root / "docs/design" / name).write_text(text)
      if lengths is not None:
        (root / "web/data").mkdir()
        (root / "web/data/lengths.json").write_text(json.dumps(lengths))
      if rules:
        # The rules' own checkout: an active constitution, which the
        # index above need not be.
        checkout = root / "rules-checkout"
        site_fixture.write(checkout)
        if edit_rules:
          edit_rules(checkout)
        out = root / "web/data/rules.json"
        args = ["--root", str(checkout), "--out", str(out)]
        if other:
          site_fixture.write_other(root / "demo")
          lock = root / "statute.lock"
          lock.write_text(
            '[[rules]]\nrule = "R3"\n\n[[rules]]\nrule = "demo:2"\n',
            encoding="utf-8",
          )
          args += ["--source", f"demo:global-private:{root / 'demo'}"]
          args += ["--enabled", str(lock)]
        self.assertEqual(site_rules.main(args), 0)
      env = dict(os.environ)
      if per_page:
        env["HUGO_PARAMS_RULESPERPAGE"] = str(per_page)
      subprocess.run(
        [
          HUGO,
          "--source",
          str(root / "web"),
          "--destination",
          str(root / "site"),
          "--panicOnWarning",
          "--quiet",
        ],
        check=True,
        timeout=HUGO_TIMEOUT,
        env=env,
      )
      pages = {
        page.relative_to(root / "site").as_posix(): page.read_text(
          encoding="utf-8"
        )
        for page in (root / "site").rglob("*.html")
      }
      return pages if raw else {p: visible(t) for p, t in pages.items()}

  @staticmethod
  def length(name: str) -> tuple[int, int, str]:
    """Return the length of a made-up file as the site gives it.

    Args:
      name: The file's key in FILES.

    Returns:
      Its characters, its words and its SHA-256.
    """
    text = count_tokens.counted(FILES[name])
    sha = hashlib.sha256(text.encode()).hexdigest()
    return len(text), len(text.split()), sha

  def test_lengths_without_tokens(self):
    pages = self.build()
    chars, words, _ = self.length("en.agent")
    full_chars, full_words, _ = self.length("en")
    self.assertIn(
      f"Revision 0.6 (draft) {chars} characters · {words} words · tokens"
      " not counted",
      pages["index.html"],
    )
    self.assertIn(
      f"Agent version {chars} {words} — Full version, this page"
      f" {full_chars} {full_words} —",
      pages["index.html"],
    )
    self.assertIn("so they were not counted.", pages["index.html"])
    self.assertIn("Counted at revision 0.6.", pages["index.html"])
    zh_chars, _, _ = self.length("zh.agent")
    self.assertIn(
      f"修订号 0.6 (草案) {zh_chars} 字符 · token 数未计算",
      pages["zh/index.html"],
    )
    self.assertIn("字符 token agent 版", pages["zh/index.html"])


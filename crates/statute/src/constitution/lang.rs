//! Everything that differs between the output languages. Adding a
//! language means adding one entry to [`LANGUAGES`] and listing it in
//! `index.toml`.

/// The strings and numbering of one output language. In the templates,
/// `{name}` is replaced by a value; `{command}` is [`super::BUILD_COMMAND`].
pub(crate) struct Language {
    pub code: &'static str,
    /// `{revision}`, `{index}`, `{articles}`: the paths of the sources.
    pub header: &'static str,
    /// `{agent}`, the path of the version for agents: follows the header
    /// when a provision is marked.
    pub legend: &'static str,
    /// `{revision}`, `{index}`, `{articles}`: the version for agents.
    pub agent_header: &'static str,
    /// In place of a marked provision's text, for agents.
    pub omitted: &'static str,
    /// `{opening}`, `{full}`, the path of the full version: in place of
    /// the front text, for agents.
    pub agent_front: &'static str,
    /// The opening while a draft.
    pub agent_draft: &'static str,
    /// The opening once active.
    pub agent_active: &'static str,
    /// `{edition}`, in the title's parentheses.
    pub edition: &'static str,
    /// `{revision}`, the revision while a draft.
    pub draft_revision: &'static str,
    /// `{anchor}`, `{number}`, `{title}`.
    pub article_heading: &'static str,
    /// `{anchor}`, `{number}`, `{note}`.
    pub repealed_article_heading: &'static str,
    /// `{number}`.
    pub article_ref: &'static str,
    /// `{article}`, `{section}`.
    pub section_ref: &'static str,
    /// Number and suffix to the article's number.
    pub article_number: fn(u64, &str) -> String,
    /// Number and suffix to the section's number.
    pub section_number: fn(u64, &str) -> String,
    /// Starts an item's list line, after its anchor.
    pub item_marker: fn(u64, &str) -> String,
    /// Follows the section's citation.
    pub item_ref: fn(u64, &str) -> String,
    /// Between item citations rendered short.
    pub connectors: &'static [&'static str],
    /// Year and month.
    pub repealed_note: fn(u64, u64) -> String,
}


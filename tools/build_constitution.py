#!/usr/bin/env python3
"""Build constitution/constitution.<lang>.md from the TOML sources.

Sources: constitution/index.toml (status, revision, languages, title and
front text), constitution/articles/<id>.toml (one article each),
constitution/sections/<id>.toml (one section each, naming its article) and
rules/<id>.toml (one rule each; checked, not rendered). The formats, the
numbering and the checks are described in docs/design.md (Source formats,
Checkers).

Without --check the sources are validated and one output per language is
written. With --check nothing is written: the sources are validated and the
committed outputs must equal a fresh build byte for byte. With --check
--base <git-ref> the numbering is also compared with that commit: once the
constitution is active, nothing numbered may disappear or change number.
Errors print as `path:line: check N: message`; the exit status is 1 on any
error.
"""

import argparse
import datetime
import re
import subprocess
import sys
import tomllib
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

INDEX = Path("constitution/index.toml")
ARTICLES = Path("constitution/articles")
SECTIONS = Path("constitution/sections")
RULES = Path("rules")
RENDERED = {"article", "section", "item"}  # kinds a rendered text may cite

ID = re.compile(r"[0-9]{8}-[a-z0-9]+(?:-[a-z0-9]+)*")
MARK = re.compile(r"\{([@#])(" + ID.pattern + r")\}")
LIST_ITEM = re.compile(r"(\s*(?:[-*+]|\d+[.)]) )")
NUMBER = re.compile(r"([1-9][0-9]*)([a-z]?)")
ITEM_NUMBER = re.compile(r"([A-Z]+)([1-9][0-9]*)([a-z]?)")
NUMBER_SHAPE = "an integer with an optional letter suffix (2, 2a)"
ITEM_NUMBER_SHAPE = "capital letters, an integer and an optional letter suffix (H2, H2a)"
MONTH = re.compile(r"([0-9]{4})-(0[1-9]|1[0-2])")
GIT_SHA = re.compile(r"[0-9a-f]{40}")

ROMAN = [
    (1000, "M"), (900, "CM"), (500, "D"), (400, "CD"), (100, "C"), (90, "XC"),
    (50, "L"), (40, "XL"), (10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I"),
]
ZH_DIGITS = "零一二三四五六七八九"
EN_MONTHS = ["January", "February", "March", "April", "May", "June", "July",
             "August", "September", "October", "November", "December"]


def roman(n: int) -> str:
    out = ""
    for value, symbol in ROMAN:
        count, n = divmod(n, value)
        out += symbol * count
    return out


def zh_number(n: int) -> str:
    if not 0 < n < 100:
        raise ValueError(f"no Chinese numeral rendering for {n}")
    tens, ones = divmod(n, 10)
    if not tens:
        return ZH_DIGITS[ones]
    return ("" if tens == 1 else ZH_DIGITS[tens]) + "十" + (ZH_DIGITS[ones] if ones else "")


def suffix_index(suffix: str) -> int:
    """The letter suffix of a number as a count: a = 1, b = 2, ..."""
    return ord(suffix) - ord("a") + 1


@dataclass(frozen=True)
class Language:
    """Everything that differs between output languages. Adding a language
    means adding one entry to LANGUAGES and listing it in index.toml."""
    header: str                        # {status}, {revision}
    article_heading: str               # {number}, {title}
    repealed_article_heading: str      # {number}, {note}
    article_ref: str                   # {number}
    section_ref: str                   # {article}, {section}
    article_number: Callable[[int, str], str]
    section_number: Callable[[int, str], str]
    repealed_note: Callable[[int, int], str]   # year, month


LANGUAGES = {
    "en": Language(
        header=(
            "Generated from `constitution/index.toml`, `constitution/articles/`"
            " and `constitution/sections/` by `tools/build_constitution.py`."
            " Do not edit this file; edit the sources and rebuild."
            " Status: {status}. Revision: {revision}. Language: English."
        ),
        article_heading="## Article {number}. {title}",
        repealed_article_heading="## Article {number} ({note})",
        article_ref="Art. {number}",
        section_ref="{article} {section}",
        article_number=lambda n, s: roman(n) + s,
        section_number=lambda n, s: f"§{n}{s}",
        repealed_note=lambda y, m: f"repealed {EN_MONTHS[m - 1]} {y}",
    ),
    "zh": Language(
        header=(
            "本文件由 `tools/build_constitution.py` 从 `constitution/index.toml`、"
            "`constitution/articles/` 和 `constitution/sections/` 生成，不要手改；"
            "改源文件后重新生成。状态：{status}。修订版：{revision}。语言：中文。"
        ),
        article_heading="## {number} {title}",
        repealed_article_heading="## {number} ({note})",
        article_ref="{number}",
        section_ref="{article}{section}",
        article_number=lambda n, s: f"第{zh_number(n)}条" + (f"之{zh_number(suffix_index(s))}" if s else ""),
        section_number=lambda n, s: f"第{zh_number(n)}款" + (f"之{zh_number(suffix_index(s))}" if s else ""),
        repealed_note=lambda y, m: f"{y} 年 {m} 月废止",
    ),
}


# Schemas: key -> type; a trailing `?` marks an optional key; LANG is a table
# whose keys are exactly the languages of index.toml and whose values are text.
LANG = "lang"
INDEX_SCHEMA = {"status": str, "revision": str, "languages": list, "title": LANG, "front": LANG}
ARTICLE_SCHEMA = {"id": str, "number": str, "repealed?": str, "title": LANG, "intro?": LANG}
SECTION_SCHEMA = {"id": str, "article": str, "number": str, "status": str, "repealed?": str,
                  "content": LANG, "items?": list}
ITEM_SCHEMA = {"id": str, "number": str, "repealed?": str}
RULE_SCHEMA = {"id": str, "status": str, "scope": str, "authority": list,
               "title": LANG, "content": LANG}
INDEX_STATUS = ("draft", "active")
STATUS = ("draft", "active", "repealed")


class Errors(list):
    def add(self, path: Path, line: int, check: int, message: str) -> None:
        self.append(f"{path}:{line}: check {check}: {message}")


@dataclass
class Doc:
    """One parsed TOML file with its text, for locating errors by line."""
    path: Path
    data: dict
    text: str

    def line(self, *needles: str) -> int:
        """The first line holding the first needle found, else 1."""
        for needle in needles:
            for n, line in enumerate(self.text.split("\n"), start=1):
                if needle in line:
                    return n
        return 1


@dataclass
class Item:
    id: str
    number: str
    repealed: str | None
    section: "Section"


@dataclass
class Article:
    doc: Doc
    id: str
    number: str
    repealed: str | None
    title: dict
    intro: dict | None


@dataclass
class Section:
    doc: Doc
    id: str
    article: str
    number: str
    status: str
    repealed: str | None
    content: dict
    items: list[Item] = field(default_factory=list)


@dataclass
class Rule:
    doc: Doc
    id: str
    status: str
    authority: list
    title: dict
    content: dict


@dataclass
class Sources:
    index: Doc
    languages: list[str]
    articles: list[Article]
    sections: list[Section]
    rules: list[Rule]
    kinds: dict = field(default_factory=dict)      # id -> article | section | item | rule
    repealed: set = field(default_factory=set)     # ids of repealed provisions

    @property
    def items(self) -> list[Item]:
        return [item for section in self.sections for item in section.items]

    def texts(self):
        """Every multilingual text: (doc, field name, lang -> text, source
        kind, source is repealed)."""
        yield self.index, "title", self.index.data["title"], "index", False
        yield self.index, "front", self.index.data["front"], "index", False
        for a in self.articles:
            yield a.doc, "title", a.title, "article", bool(a.repealed)
            if a.intro is not None:
                yield a.doc, "intro", a.intro, "article", bool(a.repealed)
        for s in self.sections:
            yield s.doc, "content", s.content, "section", s.status == "repealed"
        for r in self.rules:
            yield r.doc, "title", r.title, "rule", r.status == "repealed"
            yield r.doc, "content", r.content, "rule", r.status == "repealed"


def number_key(number: str) -> tuple:
    m = NUMBER.fullmatch(number)
    return (int(m.group(1)), m.group(2))


def item_key(number: str) -> tuple:
    m = ITEM_NUMBER.fullmatch(number)
    return (m.group(1), int(m.group(2)), m.group(3))


def marks(text: str, kind: str) -> list[str]:
    """The IDs of the `{@id}` (kind "@") or `{#id}` (kind "#") marks."""
    return [m.group(2) for m in MARK.finditer(text) if m.group(1) == kind]


# Check 1: format.

def read_toml(root: Path, path: Path, errors: Errors) -> Doc | None:
    try:
        text = (root / path).read_text(encoding="utf-8")
        data = tomllib.loads(text)
    except OSError as e:
        errors.add(path, 1, 1, f"cannot read: {e.strerror}")
        return None
    except UnicodeDecodeError:
        errors.add(path, 1, 1, "not UTF-8")
        return None
    except tomllib.TOMLDecodeError as e:
        errors.add(path, 1, 1, f"not valid TOML: {e}")
        return None
    return Doc(path, data, text)


def check_keys(doc: Doc, table: dict, schema: dict, languages: list[str] | None,
               errors: Errors, where: str = "") -> bool:
    """The table has the schema's keys, no others, with the right types;
    language tables have exactly the languages. Returns True when clean.
    The text of the language tables is normalized later by `strip_texts`."""
    before = len(errors)
    label = f"`{where}` " if where else ""
    for key, kind in schema.items():
        optional = key.endswith("?")
        name = key.rstrip("?")
        if name not in table:
            if not optional:
                errors.add(doc.path, 1, 1, f"{label}lacks `{name}`")
            continue
        value = table[name]
        line = doc.line(f"[{name}]", f"{name} =")
        if kind == LANG:
            if not isinstance(value, dict) or not all(isinstance(v, str) for v in value.values()):
                errors.add(doc.path, line, 1, f"{label}`{name}` must be a table of language to text")
            elif languages is not None and set(value) != set(languages):
                errors.add(doc.path, line, 1,
                           f"{label}`{name}` has languages {list(value)}, index.toml lists {languages}")
            elif name == "title" and any("\n" in text.strip("\n") for text in value.values()):
                errors.add(doc.path, line, 1, f"{label}`title` must be one line")
        elif not isinstance(value, kind):
            errors.add(doc.path, line, 1, f"{label}`{name}` must be a {kind.__name__}")
    for name in table.keys() - {k.rstrip("?") for k in schema}:
        errors.add(doc.path, doc.line(f"[{name}]", f"{name} ="), 1, f"{label}unknown key `{name}`")
    return len(errors) == before


def strip_texts(table: dict, schema: dict) -> None:
    """Drop the newline after the opening and before the closing quotes of
    each text of the table's language tables."""
    for key, kind in schema.items():
        name = key.rstrip("?")
        if kind == LANG and name in table:
            for lang, text in table[name].items():
                table[name][lang] = text.strip("\n")


def check_repealed(doc: Doc, table: dict, status: str | None, errors: Errors,
                   where: str = "") -> None:
    """`repealed` is a year-month and present exactly when the status says
    repealed (for articles and items: present only when repealed)."""
    label = f"`{where}` " if where else ""
    value = table.get("repealed")
    line = doc.line("repealed =")
    if value is not None and not MONTH.fullmatch(value):
        errors.add(doc.path, line, 1, f"{label}`repealed` must be `YYYY-MM`, got `{value}`")
    if status == "repealed" and value is None:
        errors.add(doc.path, doc.line("status ="), 1, f"{label}status is repealed but there is no `repealed` date")
    if status not in (None, "repealed") and value is not None:
        errors.add(doc.path, line, 1, f"{label}has `repealed` but status is {status}")


def load(root: Path, errors: Errors) -> Sources | None:
    """Check 1: read every source and check its format."""
    index = read_toml(root, INDEX, errors)
    if not index or not check_keys(index, index.data, INDEX_SCHEMA, None, errors):
        return None
    languages = index.data["languages"]
    if not languages or not all(isinstance(lang, str) for lang in languages) \
            or len(set(languages)) != len(languages):
        errors.add(INDEX, index.line("languages ="), 1, "`languages` must list each language once")
        return None
    for lang in languages:
        if lang not in LANGUAGES:
            errors.add(INDEX, index.line("languages ="), 1,
                       f"no rendering for language `{lang}`; add it to LANGUAGES in {Path(__file__).name}")
    index_status = index.data["status"]
    if index_status not in INDEX_STATUS:
        errors.add(INDEX, index.line("status ="), 1, f"`status` must be one of {INDEX_STATUS}")
    check_keys(index, index.data, INDEX_SCHEMA, languages, errors)
    if errors:
        return None
    strip_texts(index.data, INDEX_SCHEMA)

    def files(directory: Path) -> list[Path]:
        return sorted(p.relative_to(root) for p in (root / directory).glob("*.toml"))

    def own_id(doc: Doc) -> None:
        if doc.data["id"] != doc.path.stem:
            errors.add(doc.path, doc.line("id ="), 1, f"`id` must equal the file name `{doc.path.stem}`")

    def status_of(doc: Doc, what: str) -> str:
        status = doc.data["status"]
        if status not in STATUS:
            errors.add(doc.path, doc.line("status ="), 1, f"`status` must be one of {STATUS}")
        elif index_status == "draft" and status != "draft":
            errors.add(doc.path, doc.line("status ="), 1,
                       f"a {what} is {status} while index.toml is draft")
        elif index_status == "active" and what == "section" and status == "draft":
            errors.add(doc.path, doc.line("status ="), 1,
                       "a section is draft while index.toml is active")
        return status

    def number_of(doc: Doc, table: dict, pattern: re.Pattern, shape: str, where: str = "") -> None:
        if not pattern.fullmatch(table["number"]):
            errors.add(doc.path, doc.line(f'number = "{table["number"]}"'), 1,
                       f"{where}`number` `{table['number']}` is not {shape}")

    articles, sections, rules = [], [], []
    for path in files(ARTICLES):
        doc = read_toml(root, path, errors)
        if not doc or not check_keys(doc, doc.data, ARTICLE_SCHEMA, languages, errors):
            continue
        strip_texts(doc.data, ARTICLE_SCHEMA)
        own_id(doc)
        number_of(doc, doc.data, NUMBER, NUMBER_SHAPE)
        check_repealed(doc, doc.data, None, errors)
        if index_status == "draft" and "repealed" in doc.data:
            errors.add(path, doc.line("repealed ="), 1, "an article is repealed while index.toml is draft")
        d = doc.data
        articles.append(Article(doc, d["id"], d["number"], d.get("repealed"), d["title"], d.get("intro")))
    for path in files(SECTIONS):
        doc = read_toml(root, path, errors)
        if not doc or not check_keys(doc, doc.data, SECTION_SCHEMA, languages, errors):
            continue
        strip_texts(doc.data, SECTION_SCHEMA)
        own_id(doc)
        number_of(doc, doc.data, NUMBER, NUMBER_SHAPE)
        status = status_of(doc, "section")
        check_repealed(doc, doc.data, status, errors)
        d = doc.data
        section = Section(doc, d["id"], d["article"], d["number"], status, d.get("repealed"), d["content"])
        for i, item in enumerate(d.get("items", [])):
            where = f"items[{i}]"
            if not isinstance(item, dict) or not check_keys(doc, item, ITEM_SCHEMA, None, errors, where):
                continue
            number_of(doc, item, ITEM_NUMBER, ITEM_NUMBER_SHAPE, f"`{where}` ")
            check_repealed(doc, item, None, errors, where)
            if index_status == "draft" and "repealed" in item:
                errors.add(path, doc.line("repealed ="), 1, f"`{where}` is repealed while index.toml is draft")
            section.items.append(Item(item["id"], item["number"], item.get("repealed"), section))
        sections.append(section)
    for path in files(RULES):
        doc = read_toml(root, path, errors)
        if not doc or not check_keys(doc, doc.data, RULE_SCHEMA, languages, errors):
            continue
        strip_texts(doc.data, RULE_SCHEMA)
        own_id(doc)
        status = status_of(doc, "rule")
        d = doc.data
        if not d["authority"] or not all(isinstance(a, str) for a in d["authority"]):
            errors.add(path, doc.line("authority ="), 1, "`authority` must be a non-empty list of IDs")
        rules.append(Rule(doc, d["id"], status, d["authority"], d["title"], d["content"]))
    if errors:
        return None
    return Sources(index, languages, articles, sections, rules)


# Check 2: IDs.

def valid_id(value: str) -> bool:
    if not ID.fullmatch(value):
        return False
    try:
        datetime.date(int(value[:4]), int(value[4:6]), int(value[6:8]))
    except ValueError:
        return False
    return True


def check_ids(src: Sources, errors: Errors) -> None:
    """Every ID has the format with a real date, and is defined once across
    the constitution and the rules."""
    declared = [(a.doc, a.id, "article") for a in src.articles]
    declared += [(s.doc, s.id, "section") for s in src.sections]
    declared += [(i.section.doc, i.id, "item") for i in src.items]
    declared += [(r.doc, r.id, "rule") for r in src.rules]
    seen = {}
    for doc, value, kind in declared:
        line = doc.line(f'id = "{value}"')
        if not valid_id(value):
            errors.add(doc.path, line, 2, f"`{value}` is not an ID `YYYYMMDD-words` with a real date")
        if value in seen:
            errors.add(doc.path, line, 2, f"{value} is already defined at {seen[value]}")
        seen.setdefault(value, f"{doc.path}:{line}")
        src.kinds[value] = kind
    for a in src.articles:
        if a.repealed:
            src.repealed.add(a.id)
    for s in src.sections:
        if s.status == "repealed":
            src.repealed.add(s.id)
    for i in src.items:
        if i.repealed:
            src.repealed.add(i.id)
    for r in src.rules:
        if r.status == "repealed":
            src.repealed.add(r.id)


# Check 3: structure.

@dataclass
class Line:
    """One line of a section's content, split around a definition."""
    text: str
    defined: str = ""      # the ID defined at the start of the list item, or ""
    prefix: str = ""       # the list marker before the definition
    rest: str = ""         # what follows the definition
    misplaced: bool = False  # a `{#` mark sits anywhere else


def lines_of(text: str) -> list[Line]:
    out = []
    for text_line in text.split("\n"):
        line = Line(text_line)
        item = LIST_ITEM.match(text_line)
        for m in MARK.finditer(text_line):
            if m.group(1) != "#":
                continue
            if item and m.start() == item.end() and not line.defined:
                line.defined, line.prefix, line.rest = m.group(2), item.group(1), text_line[m.end():]
            else:
                line.misplaced = True
        out.append(line)
    return out


def check_structure(src: Sources, errors: Errors) -> None:
    articles = {a.id: a for a in src.articles}
    unique(errors, 3, [(a.doc, a.number, "article") for a in src.articles], number_key)
    for a in src.articles:
        own = [s for s in src.sections if s.article == a.id]
        unique(errors, 3, [(s.doc, s.number, f"section of {a.id}") for s in own], number_key)
        if a.repealed:
            for s in own:
                if s.status != "repealed":
                    errors.add(s.doc.path, s.doc.line("status ="), 3,
                               f"{s.id} is {s.status} but its article {a.id} is repealed")
    unique(errors, 3, [(i.section.doc, i.number, "item") for i in src.items], item_key)
    for s in src.sections:
        if s.article not in articles:
            errors.add(s.doc.path, s.doc.line("article ="), 3, f"article {s.article} does not exist")
        expected = [i.id for i in sorted(s.items, key=lambda i: item_key(i.number))]
        repealed = {i.id for i in s.items if i.repealed}
        for lang in src.languages:
            defined = []
            for line in lines_of(s.content[lang]):
                n = s.doc.line(line.text)
                if line.misplaced:
                    errors.add(s.doc.path, n, 3, f"a `{{#...}}` definition is not at the start of a list item")
                did = line.defined
                if not did:
                    continue
                defined.append(did)
                if did in repealed and line.rest.strip():
                    errors.add(s.doc.path, n, 3, f"repealed item {did} must have no text after `{{#{did}}}`")
                if did not in repealed and did in expected and not line.rest.strip():
                    errors.add(s.doc.path, n, 3, f"item {did} has no text")
            if lang == src.languages[0] and defined != expected:
                errors.add(s.doc.path, s.doc.line("[content]"), 3,
                           f"{lang} defines {defined}; `items` by number are {expected}")
    for doc, name, texts, kind, _ in src.texts():
        if kind != "section":
            for lang, text in texts.items():
                for did in marks(text, "#"):
                    errors.add(doc.path, doc.line(f"{{#{did}}}"), 3,
                               f"{lang} `{name}` defines {did}; only a section's content defines items")


def unique(errors: Errors, check: int, numbered: list, key: Callable) -> None:
    seen = {}
    for doc, number, what in numbered:
        k = key(number)
        line = doc.line(f'number = "{number}"')
        if k in seen:
            errors.add(doc.path, line, check, f"{what} number {number} is already used at {seen[k]}")
        seen.setdefault(k, f"{doc.path}:{line}")


# Check 4: language alignment.

def check_languages(src: Sources, errors: Errors) -> None:
    first = src.languages[0]
    for doc, name, texts, _, _ in src.texts():
        defs = {lang: marks(text, "#") for lang, text in texts.items()}
        refs = {lang: set(marks(text, "@")) for lang, text in texts.items()}
        for lang in src.languages[1:]:
            if defs[lang] != defs[first]:
                errors.add(doc.path, doc.line(f"[{name}]"), 4,
                           f"{lang} `{name}` defines {defs[lang]} where {first} defines {defs[first]}")
            for a, b in ((first, lang), (lang, first)):
                for ref in sorted(refs[a] - refs[b]):
                    errors.add(doc.path, doc.line(f"{{@{ref}}}"), 4,
                               f"{a} `{name}` cites {ref}; {b} does not")


# Check 5: references.

def check_refs(src: Sources, errors: Errors) -> None:
    for doc, name, texts, kind, repealed in src.texts():
        if repealed:
            continue
        for lang, text in texts.items():
            for ref in marks(text, "@"):
                line = doc.line(f"{{@{ref}}}")
                if ref not in src.kinds:
                    errors.add(doc.path, line, 5, f"cites undefined {ref}")
                elif ref in src.repealed:
                    errors.add(doc.path, line, 5, f"cites repealed {ref}")
                elif kind != "rule" and src.kinds[ref] not in RENDERED:
                    errors.add(doc.path, line, 5, f"the constitution cites {src.kinds[ref]} {ref}; it may only cite itself")
    for r in src.rules:
        if r.status == "repealed":
            continue
        line = r.doc.line("authority =")
        for ref in r.authority:
            if ref not in src.kinds or src.kinds[ref] not in RENDERED:
                errors.add(r.doc.path, line, 5, f"authority {ref} is not an article, section or item")
            elif ref in src.repealed:
                errors.add(r.doc.path, line, 5, f"authority {ref} is repealed")


# Rendering.

def render(lang: str, src: Sources) -> str:
    L = LANGUAGES[lang]
    labels, numbers = {}, {}
    for a in sorted(src.articles, key=lambda a: number_key(a.number)):
        numbers[a.id] = L.article_number(*number_key(a.number))
        labels[a.id] = L.article_ref.format(number=numbers[a.id])
    for s in src.sections:
        numbers[s.id] = L.section_number(*number_key(s.number))
        labels[s.id] = L.section_ref.format(article=labels[s.article], section=numbers[s.id])
    for i in src.items:
        labels[i.id] = i.number
    repealed_items = {i.id: i for i in src.items if i.repealed}

    def note(month: str) -> str:
        m = MONTH.fullmatch(month)
        return L.repealed_note(int(m.group(1)), int(m.group(2)))

    def refs(text: str) -> str:
        return MARK.sub(lambda m: labels[m.group(2)] if m.group(1) == "@" else m.group(0), text)

    def section_text(s: Section) -> str:
        lines = []
        for line in lines_of(s.content[lang]):
            if not line.defined:
                lines.append(refs(line.text))
            elif line.defined in repealed_items:
                lines.append(f"{line.prefix}{labels[line.defined]} ({note(repealed_items[line.defined].repealed)})")
            else:
                lines.append(f"{line.prefix}{labels[line.defined]}{refs(line.rest)}")
        head, *tail = lines
        return "\n".join([f"- {numbers[s.id]} {head}", *("  " + t if t else t for t in tail)])

    index = src.index.data
    parts = [L.header.format(status=index["status"], revision=index["revision"]),
             f"# {refs(index['title'][lang])}\n\n{refs(index['front'][lang])}"]
    for a in sorted(src.articles, key=lambda a: number_key(a.number)):
        if a.repealed:
            parts.append(L.repealed_article_heading.format(number=numbers[a.id], note=note(a.repealed)))
            continue
        block = [L.article_heading.format(number=numbers[a.id], title=refs(a.title[lang]))]
        if a.intro is not None:
            block.append(refs(a.intro[lang]))
        own = sorted((s for s in src.sections if s.article == a.id), key=lambda s: number_key(s.number))
        body = []
        for s in own:
            if s.status == "repealed":
                body.append(f"- {numbers[s.id]} ({note(s.repealed)})")
            else:
                body.append(section_text(s))
        if body:
            block.append("\n".join(body))
        parts.append("\n\n".join(block))
    return "\n\n".join(parts) + "\n"


def output_path(lang: str) -> Path:
    return Path(f"constitution/constitution.{lang}.md")


def build(root: Path) -> tuple[Errors, Sources | None, dict]:
    """Run checks 1 to 5 in order, stopping after the first that fails."""
    errors = Errors()
    src = load(root, errors)
    if errors:
        return errors, None, {}
    for check in (check_ids, check_structure, check_languages, check_refs):
        check(src, errors)
        if errors:
            return errors, src, {}
    return errors, src, {lang: render(lang, src) for lang in src.languages}


# Check 6: outputs.

def check_outputs(root: Path, outputs: dict, errors: Errors) -> None:
    """The committed outputs equal a fresh build byte for byte."""
    for lang, text in outputs.items():
        path = output_path(lang)
        try:
            committed = (root / path).read_bytes()
        except OSError:
            errors.add(path, 1, 6, "missing; run tools/build_constitution.py")
            continue
        built = text.encode("utf-8")
        if committed != built:
            old, new = committed.split(b"\n"), built.split(b"\n")
            pairs = enumerate(zip(old, new), start=1)
            line = next((i for i, (a, b) in pairs if a != b), min(len(old), len(new)))
            errors.add(path, line, 6, "differs from a fresh build; run tools/build_constitution.py")


# Check 7: numbering against a base commit.

def git(root: Path, *args: str) -> str | None:
    result = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else None


def check_base(root: Path, ref: str, src: Sources, errors: Errors) -> str:
    """Once the base is active: every article, section, item and rule of the
    base still exists with the same number (and article), and what was
    repealed stays repealed. Returns a note when the step is skipped."""
    if git(root, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}") is None:
        errors.add(INDEX, 1, 7, f"base `{ref}` is not a commit")
        return ""
    base_index = git(root, "show", f"{ref}:{INDEX}")
    if base_index is None:
        return f"base {ref} has no {INDEX}; numbering not compared"
    try:
        status = tomllib.loads(base_index).get("status")
    except tomllib.TOMLDecodeError as e:
        errors.add(INDEX, 1, 7, f"{INDEX} at base {ref} is not valid TOML: {e}")
        return ""
    if status != "active":
        return f"base {ref} is {status}; numbering not compared"
    if src.index.data["status"] != "active":
        errors.add(INDEX, src.index.line("status ="), 7, f"status went back to draft from active at base {ref}")

    base = {}
    listing = git(root, "ls-tree", "-r", "--name-only", ref, "--", str(ARTICLES), str(SECTIONS), str(RULES))
    for name in (listing or "").split("\n"):
        if name.endswith(".toml"):
            try:
                base[Path(name)] = tomllib.loads(git(root, "show", f"{ref}:{name}") or "")
            except tomllib.TOMLDecodeError as e:
                errors.add(Path(name), 1, 7, f"at base {ref} is not valid TOML: {e}")
    if errors:
        return ""

    current = {a.doc.path: a for a in src.articles}
    current |= {s.doc.path: s for s in src.sections}
    current |= {r.doc.path: r for r in src.rules}
    items = {i.id: i for i in src.items}

    def same(path: Path, doc: Doc, what: str, key: str, old, new) -> None:
        if old != new:
            errors.add(path, doc.line(f'{key} = "{new}"', f"{key} ="), 7,
                       f"{what} changed `{key}` from `{old}` to `{new}` since base {ref}")

    def still_repealed(path: Path, doc: Doc, what: str, was: bool, is_now: bool) -> None:
        if was and not is_now:
            errors.add(path, doc.line("repealed =", "status ="), 7,
                       f"{what} was repealed at base {ref} and is no longer")

    for path, old in sorted(base.items()):
        now = current.get(path)
        if now is None:
            errors.add(path, 1, 7, f"existed at base {ref} and is gone; repeal it instead")
            continue
        what = old.get("id", path.stem)
        same(path, now.doc, what, "id", old.get("id"), now.id)
        if path.parent == ARTICLES:
            same(path, now.doc, what, "number", old.get("number"), now.number)
            still_repealed(path, now.doc, what, "repealed" in old, bool(now.repealed))
        elif path.parent == SECTIONS:
            same(path, now.doc, what, "number", old.get("number"), now.number)
            same(path, now.doc, what, "article", old.get("article"), now.article)
            still_repealed(path, now.doc, what, old.get("status") == "repealed", now.status == "repealed")
            for item in old.get("items", []):
                iid = item.get("id")
                if iid not in items or items[iid].section is not now:
                    errors.add(path, now.doc.line("[[items]]"), 7,
                               f"item {iid} of {what} at base {ref} is gone; repeal it instead")
                    continue
                same(path, now.doc, f"item {iid}", "number", item.get("number"), items[iid].number)
                still_repealed(path, now.doc, f"item {iid}", "repealed" in item, bool(items[iid].repealed))
        else:
            still_repealed(path, now.doc, what, old.get("status") == "repealed", now.status == "repealed")
    return ""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                        help="repository root (default: the repo this script is in)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; also fail if the committed outputs are stale")
    parser.add_argument("--base", metavar="GIT_REF",
                        help="with --check: also compare the numbering with this commit")
    args = parser.parse_args(argv)
    if args.base and not args.check:
        parser.error("--base needs --check")
    errors, src, outputs = build(args.root)
    if not errors and args.check:
        check_outputs(args.root, outputs, errors)
    if not errors and args.base:
        note = check_base(args.root, args.base, src, errors)
        if note:
            print(note)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if not args.check:
        for lang, text in outputs.items():
            (args.root / output_path(lang)).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())

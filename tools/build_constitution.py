#!/usr/bin/env python3
"""Build constitution/constitution.{en,zh}.md from the per-article sources.

Sources: constitution/index.md (front matter, then the header text in both
languages) and constitution/articles/C<n>.md (one article each). The format
and the six checks are described in docs/design.md (Source formats,
Constitution).

Without --check the sources are validated and both outputs are written.
With --check nothing is written: the sources are validated and the committed
outputs must equal a fresh build byte for byte. Errors print as
`path:line: check N: message`; the exit status is 1 on any error.
"""

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

LANGS = ("en", "zh")
INDEX = Path("constitution/index.md")
ARTICLES = Path("constitution/articles")
OUTPUTS = {lang: Path(f"constitution/constitution.{lang}.md") for lang in LANGS}
INDEX_KEYS = {"status": str, "revision": str, "articles": list, "retired": list}
ARTICLE_KEYS = {"id": str}

ID = r"C\d+\.\d+|C\d+|[HAL]\d+"
MARK = re.compile(r"\{(#?)(" + ID + r")\}")
LIST_ITEM = re.compile(r"\s*(?:[-*+]|\d+[.)]) ")
ARTICLE_ID = re.compile(r"C\d+")
SECTION_ID = re.compile(r"(C\d+)\.\d+")
FRONT_LINE = re.compile(r"([a-z_]+): (.*)")

HEADER = {
    "en": (
        "Generated from `constitution/index.md` and `constitution/articles/`"
        " by `tools/build_constitution.py`. Do not edit this file; edit the"
        " sources and rebuild. Status: {status}. Revision: {revision}."
        " Language: English."
    ),
    "zh": (
        "本文件由 `tools/build_constitution.py` 从 `constitution/index.md`"
        " 和 `constitution/articles/` 生成，不要手改；改源文件后重新生成。"
        "状态：{status}。修订版：{revision}。语言：中文。"
    ),
}

ROMAN = [
    (1000, "M"), (900, "CM"), (500, "D"), (400, "CD"), (100, "C"), (90, "XC"),
    (50, "L"), (40, "XL"), (10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I"),
]
ZH_DIGITS = "零一二三四五六七八九"


def roman(n: int) -> str:
    out = ""
    for value, symbol in ROMAN:
        count, n = divmod(n, value)
        out += symbol * count
    return out


def zh_number(n: int) -> str:
    if not 0 < n < 100:
        raise ValueError(f"no Chinese numeral rendering for {n}")
    tens, ones = divmod(n, 10)
    if not tens:
        return ZH_DIGITS[ones]
    return ("" if tens == 1 else ZH_DIGITS[tens]) + "十" + (ZH_DIGITS[ones] if ones else "")


def article_label(lang: str, a: int) -> str:
    return f"Art. {roman(a)}" if lang == "en" else f"第{zh_number(a)}条"


def section_label(lang: str, s: int) -> str:
    return f"§{s}" if lang == "en" else f"第{zh_number(s)}款"


@dataclass
class Mark:
    id: str
    line: int


@dataclass
class Block:
    lines: list[str]
    first_line: int
    defs: list[Mark] = field(default_factory=list)
    refs: list[Mark] = field(default_factory=list)


@dataclass
class Source:
    path: Path
    meta: dict
    meta_lines: dict
    blocks: dict


class Errors(list):
    def add(self, path: Path, line: int, check: int, message: str) -> None:
        self.append(f"{path}:{line}: check {check}: {message}")


def parse(root: Path, path: Path, errors: Errors) -> Source | None:
    """Check 1 for one file: front matter, then the two language blocks."""
    try:
        lines = (root / path).read_text(encoding="utf-8").split("\n")
    except OSError as e:
        errors.add(path, 1, 1, f"cannot read: {e.strerror}")
        return None
    except UnicodeDecodeError:
        errors.add(path, 1, 1, "not UTF-8")
        return None
    if lines[0] != "---" or "---" not in lines[1:]:
        errors.add(path, 1, 1, "no front matter block delimited by '---' lines")
        return None
    end = lines.index("---", 1)
    meta, meta_lines = parse_front_matter(path, lines[1:end], errors)
    blocks = parse_blocks(path, lines, end, errors)
    return Source(path, meta, meta_lines, blocks) if blocks else None


def parse_front_matter(path: Path, lines: list[str], errors: Errors) -> tuple[dict, dict]:
    """The flat subset: `key: scalar` or `key: [a, b]`, exactly the required keys."""
    keys = INDEX_KEYS if path == INDEX else ARTICLE_KEYS
    meta, meta_lines = {}, {}
    for n, text in enumerate(lines, start=2):
        m = FRONT_LINE.fullmatch(text)
        if not m:
            errors.add(path, n, 1, "front matter line is not `key: value`")
            continue
        key, value = m.groups()
        if key in meta:
            errors.add(path, n, 1, f"`{key}` appears twice")
            continue
        if value.startswith("["):
            if not value.endswith("]"):
                errors.add(path, n, 1, "list value does not end with ']'")
                continue
            inner = value[1:-1].strip()
            value = [item.strip() for item in inner.split(",")] if inner else []
        meta[key], meta_lines[key] = value, n
    for key, kind in keys.items():
        if key not in meta:
            errors.add(path, 1, 1, f"front matter lacks `{key}`")
        elif not isinstance(meta[key], kind):
            errors.add(path, meta_lines[key], 1, f"`{key}` must be a {kind.__name__}")
    for key in meta.keys() - keys.keys():
        errors.add(path, meta_lines[key], 1, f"unknown front matter key `{key}`")
    return meta, meta_lines


def parse_blocks(path: Path, lines: list[str], end: int, errors: Errors) -> dict | None:
    """The en and zh blocks after the front matter (which ends at index
    `end`), with the definitions and references in each."""
    marker_at = {}
    for n, text in enumerate(lines[end + 1:], start=end + 2):
        m = re.fullmatch(r"<!-- lang: (\w+) -->", text.rstrip())
        if m:
            if m.group(1) not in LANGS or m.group(1) in marker_at:
                errors.add(path, n, 1, f"unexpected language marker `{text.strip()}`")
            marker_at.setdefault(m.group(1), n)
        elif not marker_at and text.strip():
            errors.add(path, n, 1, "text before the `<!-- lang: en -->` marker")
    if set(marker_at) != set(LANGS):
        errors.add(path, end + 1, 1,
                   "needs one `<!-- lang: en -->` and one `<!-- lang: zh -->` block")
        return None
    if marker_at["en"] > marker_at["zh"]:
        errors.add(path, marker_at["zh"], 1, "the zh block comes before the en block")
        return None

    blocks = {}
    bounds = {"en": (marker_at["en"], marker_at["zh"] - 1), "zh": (marker_at["zh"], len(lines))}
    for lang, (start, stop) in bounds.items():
        body = lines[start:stop]  # line numbers start + 1 .. stop
        first = start + 1
        while body and not body[0].strip():
            body.pop(0)
            first += 1
        while body and not body[-1].strip():
            body.pop()
        block = Block(body, first)
        for n, text in enumerate(body, start=first):
            if path != INDEX and n > first and text.startswith("## "):
                errors.add(path, n, 1, "a second `## ` title in an article block")
            item = LIST_ITEM.match(text)
            for m in MARK.finditer(text):
                if not m.group(1):
                    block.refs.append(Mark(m.group(2), n))
                elif item and m.start() == item.end():
                    block.defs.append(Mark(m.group(2), n))
                else:
                    errors.add(path, n, 1,
                               f"definition {{#{m.group(2)}}} is not at the start of a list item")
        if path != INDEX and not (body and body[0].startswith("## ")):
            errors.add(path, first, 1, f"{lang} block does not start with a `## ` title")
        blocks[lang] = block
    return blocks


def check_files(root: Path, index: Source, errors: Errors) -> list[Source]:
    """Check 2: index `articles` and the files in articles/ match one to one."""
    listed = index.meta["articles"]
    line = index.meta_lines["articles"]
    files = sorted(p.stem for p in (root / ARTICLES).glob("*.md"))
    for aid in listed:
        if not ARTICLE_ID.fullmatch(aid):
            errors.add(INDEX, line, 2, f"`{aid}` is not an article ID C<n>")
        elif listed.count(aid) > 1:
            errors.add(INDEX, line, 2, f"`{aid}` is listed more than once")
        elif aid not in files:
            errors.add(INDEX, line, 2, f"`{aid}` has no file {ARTICLES / aid}.md")
    for stem in files:
        if stem not in listed:
            errors.add(ARTICLES / f"{stem}.md", 1, 2,
                       "file is not listed in `articles` of index.md")
    if errors:
        return []
    articles = []
    for aid in dict.fromkeys(listed):
        source = parse(root, ARTICLES / f"{aid}.md", errors)
        if source and source.meta.get("id") != aid:
            errors.add(source.path, source.meta_lines.get("id", 1), 2,
                       f"`id` must equal the file name `{aid}`")
        articles.append(source)
    return articles


def check_ids(index: Source, articles: list[Source], errors: Errors) -> None:
    """Check 3: each ID defined once, Section prefix, nothing retired."""
    # Only the en block: check 4 then requires zh to define the same IDs.
    retired = set(index.meta["retired"])
    seen = {}
    for source in articles:
        aid = source.meta["id"]
        if aid in retired:
            errors.add(source.path, source.meta_lines["id"], 3, f"{aid} is retired")
        for mark in source.blocks["en"].defs:
            section = SECTION_ID.fullmatch(mark.id)
            if ARTICLE_ID.fullmatch(mark.id):
                errors.add(source.path, mark.line, 3,
                           f"article ID {mark.id} is defined by front matter, not in the text")
            elif section and section.group(1) != aid:
                errors.add(source.path, mark.line, 3,
                           f"{mark.id} is defined in article {aid}, not {section.group(1)}")
            if mark.id in retired:
                errors.add(source.path, mark.line, 3, f"{mark.id} is retired")
            if mark.id in seen:
                errors.add(source.path, mark.line, 3,
                           f"{mark.id} is already defined at {seen[mark.id]}")
            seen.setdefault(mark.id, f"{source.path}:{mark.line}")
    for lang in LANGS:
        for mark in index.blocks[lang].defs:
            errors.add(INDEX, mark.line, 3,
                       f"{mark.id} is defined in index.md; IDs are defined in articles")


def check_languages(sources: list[Source], errors: Errors) -> None:
    """Check 4: en and zh define the same IDs in order and cite the same IDs."""
    for source in sources:
        en, zh = source.blocks["en"], source.blocks["zh"]
        en_defs, zh_defs = [m.id for m in en.defs], [m.id for m in zh.defs]
        if en_defs != zh_defs:
            pairs = enumerate(zip(en_defs, zh_defs))
            i = next((i for i, (a, b) in pairs if a != b), min(len(en_defs), len(zh_defs)))
            line = zh.defs[i].line if i < len(zh.defs) else zh.first_line
            got, want = zh_defs[i:i + 1] or "nothing", en_defs[i:i + 1] or "nothing"
            errors.add(source.path, line, 4,
                       f"zh defines {got} where en defines {want} (definition {i + 1})")
        en_refs, zh_refs = {m.id for m in en.refs}, {m.id for m in zh.refs}
        for lang, block, other in (("en", en, zh_refs), ("zh", zh, en_refs)):
            for mark in block.refs:
                if mark.id not in other:
                    errors.add(source.path, mark.line, 4,
                               f"{lang} cites {mark.id}; the other language does not")


def check_refs(index: Source, articles: list[Source], errors: Errors) -> None:
    """Check 5: every reference resolves and none points to a retired ID."""
    retired = set(index.meta["retired"])
    defined = {s.meta["id"] for s in articles}
    defined |= {m.id for s in articles for m in s.blocks["en"].defs}
    for source in [index, *articles]:
        for lang in LANGS:
            for mark in source.blocks[lang].refs:
                if mark.id in retired:
                    errors.add(source.path, mark.line, 5, f"cites retired {mark.id}")
                elif mark.id not in defined:
                    errors.add(source.path, mark.line, 5, f"cites undefined {mark.id}")


def render(lang: str, index: Source, articles: list[Source]) -> str:
    numbers = {}  # ID -> (article number, section number or None)
    for a, source in enumerate(articles, start=1):
        numbers[source.meta["id"]] = (a, None)
        sections = [m.id for m in source.blocks[lang].defs if SECTION_ID.fullmatch(m.id)]
        for s, sid in enumerate(sections, start=1):
            numbers[sid] = (a, s)

    def mark(m: re.Match) -> str:
        definition, mid = m.groups()
        if mid not in numbers:  # H, A and L items show their ID as is
            return mid
        a, s = numbers[mid]
        if definition:
            return f"{section_label(lang, s)} ({mid})"
        if s is None:
            return article_label(lang, a)
        return article_label(lang, a) + (" " if lang == "en" else "") + section_label(lang, s)

    def text(lines: list[str]) -> str:
        return "\n".join(MARK.sub(mark, line) for line in lines)

    header = HEADER[lang].format(status=index.meta["status"], revision=index.meta["revision"])
    parts = [header, text(index.blocks[lang].lines)]
    for a, source in enumerate(articles, start=1):
        title, *body = source.blocks[lang].lines
        aid = source.meta["id"]
        if lang == "en":
            heading = f"## Article {roman(a)}. {title[3:]} ({aid})"
        else:
            heading = f"## 第{zh_number(a)}条 {title[3:]} ({aid})"
        while body and not body[0].strip():
            body.pop(0)
        parts.append(text([heading, "", *body]) if body else text([heading]))
    return "\n\n".join(p for p in parts if p) + "\n"


def build(root: Path) -> tuple[Errors, dict]:
    """Run checks 1 to 5 in order, stopping after the first that fails."""
    errors = Errors()
    index = parse(root, INDEX, errors)
    if errors:
        return errors, {}
    articles = check_files(root, index, errors)
    if errors:
        return errors, {}
    check_ids(index, articles, errors)
    if errors:
        return errors, {}
    check_languages([index, *articles], errors)
    if errors:
        return errors, {}
    check_refs(index, articles, errors)
    if errors:
        return errors, {}
    return errors, {lang: render(lang, index, articles) for lang in LANGS}


def check_outputs(root: Path, outputs: dict, errors: Errors) -> None:
    """Check 6: the committed outputs equal a fresh build byte for byte."""
    for lang, text in outputs.items():
        path = OUTPUTS[lang]
        try:
            committed = (root / path).read_bytes()
        except OSError:
            errors.add(path, 1, 6, "missing; run tools/build_constitution.py")
            continue
        built = text.encode("utf-8")
        if committed != built:
            old, new = committed.split(b"\n"), built.split(b"\n")
            pairs = enumerate(zip(old, new), start=1)
            line = next((i for i, (a, b) in pairs if a != b), min(len(old), len(new)))
            errors.add(path, line, 6, "differs from a fresh build; run tools/build_constitution.py")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                        help="repository root (default: the repo this script is in)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; also fail if the committed outputs are stale")
    args = parser.parse_args(argv)
    errors, outputs = build(args.root)
    if not errors and args.check:
        check_outputs(args.root, outputs, errors)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if not args.check:
        for lang, text in outputs.items():
            (args.root / OUTPUTS[lang]).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())

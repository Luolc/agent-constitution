class Tree(unittest.TestCase):
    """A valid source tree in a temporary directory, edited per test."""

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        for name, text in FILES.items():
            self.write(name, text)

    def write(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def edit(self, name, old, new, count=1):
        path = self.root / name
        text = path.read_text(encoding="utf-8")
        self.assertIn(old, text)
        path.write_text(text.replace(old, new, count), encoding="utf-8")

    def move(self, old, new):
        (self.root / new).parent.mkdir(parents=True, exist_ok=True)
        (self.root / old).rename(self.root / new)

    def activate(self):
        """Make the tree active: index, sections, items and rules."""
        self.edit("constitution/index.toml", 'status = "draft"', 'status = "active"')
        self.edit("constitution/index.toml", 'revision = "0.2"', 'revision = "1"')
        for name in SECTIONS + ["rules/rule.toml"]:
            self.edit(name, 'status = "draft"', 'status = "active"', -1)

    def errors(self):
        errors, _, _ = bc.build(self.root)
        return errors

    def assertFails(self, check, location, message):
        errors = self.errors()
        self.assertTrue(errors, "expected an error, got none")
        self.assertTrue(all(f": check {check}: " in e for e in errors), errors)
        self.assertIn(f"{location}: check {check}: {message}", errors)


class RenderTest(Tree):
    def test_valid_tree_renders_both_languages(self):
        errors, _, outputs = bc.build(self.root)
        self.assertEqual(errors, [])
        self.assertEqual(outputs, {"en": EN, "zh": ZH})

    def test_write_then_check(self):
        self.assertEqual(bc.main(["--root", str(self.root)]), 0)
        self.assertEqual((self.root / "constitution/constitution.zh.md").read_bytes(), ZH.encode())
        self.assertEqual(bc.main(["--root", str(self.root), "--check"]), 0)

    def test_old_layout_is_not_read(self):
        self.write("constitution/articles/gamma.toml", "not toml [")
        self.write("constitution/sections/gamma-one.toml", "not toml [")
        self.assertEqual(self.errors(), [])

    def test_repealed_placeholders(self):
        self.activate()
        self.edit(f"{B}/01-beta-one.toml", 'status = "active"', 'status = "repealed"\nrepealed = "2026-11"')
        self.edit(f"{A}/01-alpha-one.toml", 'number = "2"\nstatus = "active"',
                  'number = "2"\nstatus = "repealed"\nrepealed = "2026-11"')
        self.write("constitution/articles/03-gamma/article.toml",
                   BETA.replace('"beta"', '"gamma"').replace("[title]", 'repealed = "2026-12"\n\n[title]'))
        # A citation of a repealed section would be an error; move it.
        self.edit(f"{A}/01-alpha-one.toml", "{@beta-one}", "{@beta-two}", 2)
        self.edit("rules/rule.toml", "{@constitution:beta-one}", "{@constitution:beta-two}", 2)
        errors, _, outputs = bc.build(self.root)
        self.assertEqual(errors, [])
        self.assertIn("\n  - (2) (repealed November 2026)\n", outputs["en"])
        self.assertIn("\n- §1 (repealed November 2026)\n", outputs["en"])
        self.assertTrue(outputs["en"].endswith("## Article III (repealed December 2026)\n"))
        self.assertIn("\n  - （二） (2026 年 11 月废止)\n", outputs["zh"])
        self.assertIn("\n- 第一款 (2026 年 11 月废止)\n", outputs["zh"])
        self.assertTrue(outputs["zh"].endswith("## 第三条 (2026 年 12 月废止)\n"))

    def test_inserted_item(self):
        self.edit(f"{A}/01-alpha-one.toml", 'id = "machines"\nnumber = "2"', 'id = "machines"\nnumber = "1a"')
        self.edit(f"{B}/01-beta-one.toml", "{@alpha-one.money}", "{@alpha-one.machines}", 2)
        errors, _, outputs = bc.build(self.root)
        self.assertEqual(errors, [])
        self.assertIn("\n  - (1a) Machines;", outputs["en"])
        self.assertIn("- §1 Four, see Art. I §1(1a) and", outputs["en"])
        self.assertIn("\n  - （一之一）机器；", outputs["zh"])
        self.assertIn("- 第一款 四，见第一条第一款第一项之一和", outputs["zh"])

    def test_numerals(self):
        self.assertEqual([bc.roman(n) for n in (1, 4, 9, 14, 40)], ["I", "IV", "IX", "XIV", "XL"])
        self.assertEqual([bc.zh_number(n) for n in (1, 10, 11, 20, 23)],
                         ["一", "十", "十一", "二十", "二十三"])
        en, zh = bc.LANGUAGES["en"], bc.LANGUAGES["zh"]
        self.assertEqual(en.section_number(12, ""), "§12")
        self.assertEqual(zh.section_number(12, "a"), "第十二款之一")
        self.assertEqual(en.item_ref(3, "b"), "(3b)")
        self.assertEqual(zh.item_ref(3, "b"), "第三项之二")
        self.assertEqual(zh.item_marker(12, ""), "（十二）")



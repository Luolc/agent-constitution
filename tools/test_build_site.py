  def test_header_list(self):
    """Under the title, a list: the revision, then the length.

    The length is that of the version for agents, bare, with the info
    button.
    """
    cases = [
      ("en", None, "15 characters · 3 words · tokens not counted"),
      ("en", 345, "15 characters · 3 words · 345 tokens"),
      ("zh", None, "11 字符 · token 数未计算"),
      ("zh", 345, "11 字符 · 345 token"),
    ]
    for lang, tokens, line in cases:
      with self.subTest(lang=lang, tokens=tokens):
        labels = build_site.PAGES[lang]
        out = build_site.page(
          SHORT[lang], AGENT[lang], labels, "0.6", None, 12345, tokens
        )
        self.assertIn(
          f'\n<ul class="revision"><li class="number">{labels["revision"]} '
          "0.6</li>"
          f'<li class="length">{line}<span class="count-info">',
          out,
        )

  def test_draft_marks_the_revision(self):
    """While a draft, both pages mark the revision; once active, neither."""
    cases = [("en", "Revision 0.6 (draft)"), ("zh", "修订号 0.6 (草案)")]
    for lang, line in cases:
      labels = build_site.PAGES[lang]
      for draft in (True, False):
        with self.subTest(lang=lang, draft=draft):
          item = line if draft else f"{labels['revision']} 0.6"
          for out in (
            build_site.page(
              SHORT[lang], AGENT[lang], labels, "0.6", None, None, None, draft
            ),
            build_site.agent_page(AGENT[lang], labels, "0.6", draft),
          ):
            self.assertIn(f'<li class="number">{item}</li>', out)


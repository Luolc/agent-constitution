def plain(text: str) -> str:
  """Strip anchors, bold and link markup, for tests about rendered words.

  Args:
    text: The rendered Markdown.

  Returns:
    The text without the markup.
  """
  text = re.sub(r'<a id="[^"]+"></a>', "", text).replace("**", "")
  return re.sub(r"\[([^\]]+)\]\[[^\]]+\]", r"\1", text)


class Tree(unittest.TestCase):
  """A valid source tree in a temporary directory, edited per test."""

  def setUp(self):
    tmp = tempfile.TemporaryDirectory()
    self.addCleanup(tmp.cleanup)
    self.root = Path(tmp.name)
    for name, text in FILES.items():
      self.write(name, text)

  def write(self, name, text):
    path = self.root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")

  def edit(self, name, old, new, count=1):
    path = self.root / name
    text = path.read_text(encoding="utf-8")
    self.assertIn(old, text)
    path.write_text(text.replace(old, new, count), encoding="utf-8")

  @contextlib.contextmanager
  def edited(self, name: str, old: str, new: str) -> Iterator[None]:
    """Edit a file for the block, and restore it after, even on a failure.

    Args:
      name: the file, relative to the root.
      old: the text to replace.
      new: the text to put in its place.

    Yields:
      Nothing; the file holds `new` inside the block.
    """
    path = self.root / name
    text = path.read_text(encoding="utf-8")
    self.edit(name, old, new)
    try:
      yield
    finally:
      path.write_text(text, encoding="utf-8")

  def move(self, old, new):
    (self.root / new).parent.mkdir(parents=True, exist_ok=True)
    (self.root / old).rename(self.root / new)

  def activate(self):
    """Make the tree active: index, sections, items and rules."""
    self.edit(
      "constitution/2026-10/index.toml", 'status = "draft"', 'status = "active"'
    )
    self.edit(
      "constitution/2026-10/index.toml", 'revision = "0.2"', 'revision = "1"'
    )
    for name in SECTIONS + NODES:
      self.edit(name, 'status = "draft"', 'status = "active"', -1)

  def rehash(self, name: str) -> None:
    """Record the current original's hash for each translation of a node.

    Args:
      name: the node's file.
    """
    path = self.root / name
    text = path.read_text(encoding="utf-8")
    data = tomllib.loads(text)
    lang = data["lang"]
    texts = [data["title"]] + [
      data["text"][p] for p in ("statement", "reason", "verification")
    ] * ("text" in data)
    new = original(*(t[lang] for t in texts))
    path.write_text(
      re.sub(r'(?m)^(\w+) = "[0-9a-f]{64}"$', rf'\1 = "{new}"', text),
      encoding="utf-8",
    )

  def assertError(self, check, path, message):  # noqa: N802
    errors = self.errors()
    pattern = re.compile(rf"{re.escape(path)}:\d+: check {check}: ")
    self.assertTrue(
      any(pattern.match(e) and e.endswith(message) for e in errors), errors
    )

  def errors(self):
    errors, _, _ = bc.build(self.root)
    return errors

  def assertFails(self, check, location, message):  # noqa: N802
    errors = self.errors()
    self.assertTrue(errors, "expected an error, got none")
    self.assertTrue(all(f": check {check}: " in e for e in errors), errors)
    self.assertIn(f"{location}: check {check}: {message}", errors)

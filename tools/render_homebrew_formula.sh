#!/usr/bin/env bash
# Renders the Homebrew formula of statute for one Release tag.
#
#   tools/render_homebrew_formula.sh statute-v0.1.17 <assets-dir> <out-file>
#
# <assets-dir> holds the Release's `statute-<target>.sha256` sidecars (what
# `gh release download --pattern 'statute-*.sha256'` leaves). Only the
# sidecars are read: the formula points Homebrew at the Release tarballs with
# their digests, and Homebrew downloads and checks them; nothing is compiled.
# What varies between releases is the tag and the four digests; the rest is
# the template below.
set -euo pipefail

if [ "$#" -ne 3 ]; then
  echo "usage: $0 <tag> <assets-dir> <out-file>" >&2
  exit 2
fi

tag="$1"
assets="$2"
out="$3"

# The tag goes into the download URLs, so it has to be a release tag.
if [[ ! $tag =~ ^statute-v([0-9]+\.[0-9]+\.[0-9]+)$ ]]; then
  echo "$0: \`$tag\` is not a statute-v<major>.<minor>.<patch> tag" >&2
  exit 1
fi
version="${BASH_REMATCH[1]}"

# A missing or malformed sidecar stops the run here, not in a user's
# `brew install`.
digest() {
  local file value
  file="$assets/statute-$1.sha256"
  [ -f "$file" ] || {
    echo "$0: no sidecar at $file" >&2
    exit 1
  }
  value="$(cut -d' ' -f1 <"$file")"
  [[ $value =~ ^[0-9a-f]{64}$ ]] || {
    echo "$0: $file does not hold a sha256 digest" >&2
    exit 1
  }
  printf '%s' "$value"
}

darwin_arm="$(digest aarch64-apple-darwin)"
darwin_intel="$(digest x86_64-apple-darwin)"
linux_arm="$(digest aarch64-unknown-linux-musl)"
linux_intel="$(digest x86_64-unknown-linux-musl)"

base="https://github.com/Luolc/agent-constitution/releases/download/$tag"

# `version` is declared: Homebrew scans GitHub Release URLs for a version only
# when the tag is `v<version>` or `<version>`, and from
# `statute-x86_64-apple-darwin` it would read `64-apple-darwin`.
# tools/check_formula_version.sh asserts what Homebrew reads.
#
# The test runs `statute validate` on a valid and on a broken rules
# directory, so a binary that starts but checks nothing fails it.
cat >"$out" <<FORMULA
# Generated by tools/render_homebrew_formula.sh in Luolc/agent-constitution.
# The next release overwrites edits here; change the template there instead.
class Statute < Formula
  desc "Compile a constitution and rules into instruction files for coding agents"
  homepage "https://github.com/Luolc/agent-constitution"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/statute-aarch64-apple-darwin.tar.gz"
      sha256 "$darwin_arm"
    end
    on_intel do
      url "$base/statute-x86_64-apple-darwin.tar.gz"
      sha256 "$darwin_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/statute-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/statute-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "statute"
  end

  test do
    assert_match "statute #{version}", shell_output("#{bin}/statute --version")

    mkdir "rules"
    assert_match "0 nodes, no errors", shell_output("#{bin}/statute validate rules")

    (testpath/"rules/1.toml").write("id = \"one\"\n")
    assert_match "rules/1.toml: error", shell_output("#{bin}/statute validate rules 2>&1", 1)
  end
end
FORMULA

# Check what was written: four digests and four URLs of this tag.
count="$(grep -c '^      sha256 "[0-9a-f]\{64\}"$' "$out")"
[ "$count" -eq 4 ] || {
  echo "$0: expected 4 sha256 lines in $out, found $count" >&2
  exit 1
}
count="$(grep -c "releases/download/$tag/statute-" "$out")"
[ "$count" -eq 4 ] || {
  echo "$0: expected 4 $tag download URLs in $out, found $count" >&2
  exit 1
}
echo "rendered $out for $tag"

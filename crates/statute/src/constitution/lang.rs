fn roman(mut n: u32) -> String {
    const ROMAN: [(u32, &str); 13] = [
        (1000, "M"),
        (900, "CM"),
        (500, "D"),
        (400, "CD"),
        (100, "C"),
        (90, "XC"),
        (50, "L"),
        (40, "XL"),
        (10, "X"),
        (9, "IX"),
        (5, "V"),
        (4, "IV"),
        (1, "I"),
    ];
    let mut out = String::new();
    for (value, symbol) in ROMAN {
        while n >= value {
            out.push_str(symbol);
            n -= value;
        }
    }
    out
}

/// n in Chinese numerals, for 1 to 99: 十四, 二十.
fn zh_number(n: u32) -> Option<String> {
    const DIGITS: [&str; 10] = ["零", "一", "二", "三", "四", "五", "六", "七", "八", "九"];
    if !(1..100).contains(&n) {
        return None;
    }
    let (tens, ones) = ((n / 10) as usize, (n % 10) as usize);
    if tens == 0 {
        return Some(DIGITS[ones].to_string());
    }
    Some(format!(
        "{}十{}",
        if tens == 1 { "" } else { DIGITS[tens] },
        if ones == 0 { "" } else { DIGITS[ones] }
    ))
}

/// n in Chinese numerals; n itself where there is none (from 100).
fn zh(n: u64) -> String {
    u32::try_from(n)
        .ok()
        .and_then(zh_number)
        .unwrap_or_else(|| n.to_string())
}

/// The letter suffix of a number in Chinese: a is 之一, b is 之二.
fn zh_suffix(suffix: &str) -> String {
    match suffix.bytes().next() {
        Some(b) => format!("之{}", zh(u64::from(b - b'a') + 1)),
        None => String::new(),
    }
}

fn en_roman(n: u64) -> String {
    roman(u32::try_from(n).unwrap_or(u32::MAX))
}


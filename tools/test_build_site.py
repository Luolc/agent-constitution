class PageTest(unittest.TestCase):
    def test_built_constitution_in_each_language(self):
        for lang, labels in build_site.PAGES.items():
            with self.subTest(lang=lang):
                md = (ROOT / f"constitution/constitution.{lang}.md").read_text(encoding="utf-8")
                agent = (ROOT / f"constitution/constitution.{lang}.agent.md").read_text(encoding="utf-8")
                title = md.split("\n")[2]
                out = build_site.page(md, agent, labels, "0.6", "abc1234", None, None)
                self.assertTrue(out.startswith(f'+++\ntitle = "{title[2:]}"\n+++\n<div class="constitution">\n'))
                self.assertIn(f'{title}\n\n<ul class="revision"><li class="number">{labels["revision"]} 0.6</li>', out)
                self.assertIn('<li class="legend">', out)
                self.assertNotIn("tools/build_constitution.py", out)
                self.assertTrue(out.endswith("\n</div>\n"))
                self.assertIn(" {#general-provisions}\n", out)
                self.assertNotIn("## <a id=", out)

    def test_other_first_line(self):
        with self.assertRaises(ValueError):
            build_site.split("# Title\n\nText.\n")

    def test_header_list(self):
        """Under the title, a list: the revision, then the length of the
        version for agents, bare, with the info button."""
        cases = [
            ("en", None, "15 characters · 3 words · tokens not counted"),
            ("en", 345, "15 characters · 3 words · 345 tokens"),
            ("zh", None, "11 字符 · token 数未计算"),
            ("zh", 345, "11 字符 · 345 token"),
        ]
        for lang, tokens, line in cases:
            with self.subTest(lang=lang, tokens=tokens):
                labels = build_site.PAGES[lang]
                out = build_site.page(SHORT[lang], AGENT[lang], labels, "0.6", None, 12345, tokens)
                self.assertIn(f'\n<ul class="revision"><li class="number">{labels["revision"]} 0.6</li>'
                              f'<li class="length">{line}<span class="count-info">', out)

    def test_popup(self):
        """The lengths of both versions in a table first, then how they were
        counted, then the link to the version for agents."""
        cases = [
            ("en", 12345, 345, "abc1234",
             ["", "characters", "words", "tokens", "For agents", "15", "3", "345", "Full, this page", "25", "5", "12,345"],
             ["Tokens counted by Anthropic's token counting API (count_tokens) for claude-opus-5-5.",
              "The version for agents leaves out the preamble, keeps only a pointer to the full version for the"
              " other parts marked *, and has no anchors or links.",
              "Counted at revision 0.6, commit abc1234."]),
            ("en", None, None, None,
             ["", "characters", "words", "tokens", "For agents", "15", "3", "—", "Full, this page", "25", "5", "—"],
             ["Tokens are counted by Anthropic's token counting API (count_tokens) for claude-opus-5-5; this build"
              " had no credential for it, or the call failed, so they were not counted.",
              "The version for agents leaves out the preamble, keeps only a pointer to the full version for the"
              " other parts marked *, and has no anchors or links.",
              "Counted at revision 0.6."]),
            ("zh", 12345, 345, "abc1234",
             ["", "字符", "token", "agent 版", "11", "345", "完整版 (本页)", "15", "12,345"],
             ["token 数由 Anthropic 的 token 计数接口 (count_tokens) 按 claude-opus-5-5 计算。",
              "agent 版不含序言，其余标 * 的部分只留一句「见完整版」，也不含锚点和链接。",
              "按修订号 0.6、commit abc1234 计算。"]),
            ("zh", None, None, None,
             ["", "字符", "token", "agent 版", "11", "—", "完整版 (本页)", "15", "—"],
             ["token 数按 Anthropic 的 token 计数接口 (count_tokens) 以 claude-opus-5-5 计数；这次构建没有凭证，或者调用失败，未计算。",
              "agent 版不含序言，其余标 * 的部分只留一句「见完整版」，也不含锚点和链接。",
              "按修订号 0.6 计算。"]),
        ]
        for lang, tokens, agent_tokens, commit, table, notes in cases:
            with self.subTest(lang=lang, tokens=tokens):
                labels = build_site.PAGES[lang]
                out = build_site.page(SHORT[lang], AGENT[lang], labels, "0.6", commit, tokens, agent_tokens)
                self.assertIn('<button type="button" class="count-button" aria-expanded="false"'
                              f' aria-controls="count-popup" aria-label="{labels["info"]}"><svg', out)
                popup = out.split('<span class="count-popup" id="count-popup">')[1].split("</span></span></li>")[0]
                self.assertTrue(popup.startswith(f'<span class="count-summary">{labels["summary"]}</span>'
                                                 '<span class="count-table"><span class="count-row">'))
                self.assertEqual(re.findall(r'<span class="count-(?:label|cell)">([^<]*)</span>', popup), table)
                self.assertEqual(re.findall(r'<span class="count-note">([^<]*)</span>', popup), notes)
                self.assertTrue(popup.endswith(f'</span><a class="count-link" href="{labels["home"]}agent/">'
                                               f'{labels["agent_link"]}</a>'))

    def test_agent_page(self):
        for lang, labels in build_site.PAGES.items():
            with self.subTest(lang=lang):
                md = (ROOT / f"constitution/constitution.{lang}.agent.md").read_text(encoding="utf-8")
                title = md.split("\n")[2]
                out = build_site.agent_page(md, labels, "0.6")
                self.assertTrue(out.startswith(f'+++\ntitle = "{title[2:]}"\nbookHidden = true\n+++\n'
                                               '<div class="constitution">\n'))
                self.assertIn(f'{title} {{anchor=false}}\n\n<p class="revision">{labels["revision"]} 0.6<br>'
                              f'<span class="back"><a href="{labels["home"]}">{labels["back"]}</a></span></p>\n', out)
                text = out.split("</p>\n", 1)[1]
                lines = text.split("\n")
                headings = [line for line in lines if line.startswith("#")]
                self.assertEqual(len(headings), md.count("\n## "))
                for heading in headings:
                    self.assertTrue(heading.endswith(" {anchor=false}"), heading)
                self.assertEqual([line.removesuffix(" {anchor=false}") for line in lines[:-3]], md.split("\n")[3:])
                for anchor_or_link in ("<a ", "](", "{#", "\n[", build_site.OMITTED_MARK):
                    self.assertNotIn(anchor_or_link, text)

    def test_legend_when_a_provision_is_marked(self):
        """The legend says in words what the asterisk marks and links to the
        version for agents; the asterisk in it is not a superscript."""
        legends = {
            "en": ('<li class="legend">Parts marked <span class="mark">*</span> are about how this constitution came'
                   ' about, is organized and is amended, and are shown to people by default; <a href="/agent/">the'
                   ' version compiled for agents</a> leaves out their text by default.</li></ul>\n'),
            "zh": ('<li class="legend">标 <span class="mark">*</span> 的部分讲本宪法的由来、编排和修改，默认只对人可见；'
                   '<a href="/zh/agent/">给 agent 编译的版本</a>默认不收录它们的正文。</li></ul>\n'),
        }
        for lang, legend in legends.items():
            with self.subTest(lang=lang):
                labels = build_site.PAGES[lang]
                self.assertNotIn('class="legend"', build_site.page(SHORT[lang], AGENT[lang], labels, "0.6", None,
                                                                   None, None))
                marked = SHORT[lang] + f"\n-   **§2**{build_site.OMITTED_MARK} Text.\n"
                out = build_site.page(marked, AGENT[lang], labels, "0.6", None, None, None)
                self.assertIn(f"</span></span></li>{legend}", out)


class CountTokensTest(unittest.TestCase):
    def count(self, environ=None, **urlopen):
        auth = build_site.credential(environ or {build_site.KEY_VARIABLE: KEY})
        stderr = io.StringIO()
        with mock.patch("urllib.request.urlopen", **urlopen) as opened, contextlib.redirect_stderr(stderr):
            tokens = build_site.count_tokens("One two three.", auth)
        return tokens, opened, stderr.getvalue()

    def test_no_credential(self):
        for environ in ({}, {build_site.KEY_VARIABLE: "", build_site.TOKEN_VARIABLE: ""}):
            with self.subTest(environ=environ):
                self.assertIsNone(build_site.credential(environ))
        with mock.patch("urllib.request.urlopen") as opened:
            self.assertIsNone(build_site.count_tokens("One two three.", None))
        opened.assert_not_called()

    def test_counted(self):
        both = {build_site.KEY_VARIABLE: KEY, build_site.TOKEN_VARIABLE: TOKEN}
        cases = [
            ({build_site.KEY_VARIABLE: KEY}, {"X-api-key": KEY}),
            ({build_site.TOKEN_VARIABLE: TOKEN}, {"Authorization": f"Bearer {TOKEN}"}),
            (both, {"Authorization": f"Bearer {TOKEN}"}),
        ]
        for environ, auth in cases:
            with self.subTest(environ=environ):
                response = mock.MagicMock()
                response.__enter__.return_value = io.BytesIO(b'{"input_tokens": 12345}')
                tokens, opened, stderr = self.count(environ, return_value=response)
                self.assertEqual(tokens, 12345)
                self.assertEqual(stderr, "")
                request = opened.call_args.args[0]
                self.assertEqual(request.full_url, "https://api.anthropic.com/v1/messages/count_tokens")
                sent = {name: request.get_header(name) for name in ("X-api-key", "Authorization")}
                self.assertEqual({name: value for name, value in sent.items() if value}, auth)
                self.assertIn(b'"model": "claude-opus-5-5"', request.data)

    def test_failures(self):
        cases = [
            (urllib.error.HTTPError("https://api.anthropic.com/", 401, "Unauthorized", {}, None), "HTTP 401"),
            (TimeoutError("timed out"), "TimeoutError"),
            (urllib.error.URLError("no route"), "URLError"),
            (http.client.IncompleteRead(b'{"input_'), "IncompleteRead"),
        ]
        for error, shown in cases:
            with self.subTest(shown=shown):
                tokens, _, stderr = self.count(side_effect=error)
                self.assertIsNone(tokens)
                self.assertEqual(stderr, f"token count: {shown}; tokens not counted\n")


class RequireTokensTest(unittest.TestCase):
    """main with Hugo and the site check mocked: a page without its token
    count fails the build only under --require-tokens."""

    def main(self, argv, environ, urlopen):
        stderr = io.StringIO()
        content = {}

        def hugo(command):
            directory = Path(command[command.index("--contentDir") + 1])
            content.update({path.name: path.read_text(encoding="utf-8") for path in directory.iterdir()})
            return mock.Mock(returncode=0)

        with (mock.patch.dict(build_site.os.environ, environ, clear=True),
              mock.patch("urllib.request.urlopen", **urlopen) as opened,
              mock.patch("build_site.short_commit", return_value="abc1234"),
              mock.patch("subprocess.run", side_effect=hugo) as run,
              mock.patch("check_site_anchors.main", return_value=0),
              contextlib.redirect_stderr(stderr)):
            code = build_site.main(["--out", "/nonexistent-site", *argv])
        self.opened, self.content = opened, content
        return code, run.called, stderr.getvalue()

    def test_tokens_not_counted(self):
        failed = {"side_effect": urllib.error.HTTPError("https://api.anthropic.com/", 401, "Unauthorized", {}, None)}
        for name, environ in (("no credential", {}), ("count fails", {build_site.TOKEN_VARIABLE: TOKEN})):
            with self.subTest(name):
                self.assertEqual(self.main([], environ, failed)[:2], (0, True))
                code, built, stderr = self.main(["--require-tokens"], environ, failed)
                self.assertEqual((code, built), (1, False))
                self.assertIn("tokens not counted", stderr)
                self.assertNotIn(TOKEN, stderr)

    def test_tokens_counted(self):
        response = mock.MagicMock()
        response.__enter__.side_effect = lambda: io.BytesIO(b'{"input_tokens": 12345}')
        code, built, _ = self.main(["--require-tokens"], {build_site.TOKEN_VARIABLE: TOKEN}, {"return_value": response})
        self.assertEqual((code, built), (0, True))
        sent = [call.args[0].data.decode() for call in self.opened.call_args_list]
        self.assertEqual(len(sent), 4)
        for lang in build_site.PAGES:
            for version in ("", ".agent"):
                md = (ROOT / f"constitution/constitution.{lang}{version}.md").read_text(encoding="utf-8")
                self.assertEqual(sum(build_site.json.dumps(build_site.counted(md)) in data for data in sent), 1)

    def test_pages_written(self):
        """Both versions of each language become a page, and they link each
        other."""
        self.main([], {}, {})
        self.assertEqual(sorted(self.content), ["_index.md", "_index.zh.md", "agent.md", "agent.zh.md"])
        for labels in build_site.PAGES.values():
            self.assertIn(f'<a class="count-link" href="{labels["home"]}agent/">{labels["agent_link"]}</a>',
                          self.content[labels["file"]])
            self.assertIn(f'<a href="{labels["home"]}">{labels["back"]}</a>', self.content[labels["agent_file"]])
            self.assertIn("commit abc1234", self.content[labels["file"]])


class CheckTest(unittest.TestCase):
    def test_every_link_has_its_target(self):
        self.assertEqual(check_site_anchors.check(GOOD), [])

    def test_broken_link(self):
        broken = GOOD.replace('href="#terms.principal"', 'href="#terms.missing"')
        self.assertEqual(check_site_anchors.check(broken), ["link #terms.missing has no target on the page"])

    def test_links_to_other_pages(self):
        with tempfile.TemporaryDirectory() as site:
            site = Path(site)
            (site / "agent").mkdir()
            (site / "agent/index.html").write_text("")
            (site / "index.html").write_text("")
            links = '<a href="./agent/">a</a><a href="agent/index.html#x">b</a><a href="https://example.test/">c</a>'
            self.assertEqual(check_site_anchors.check(GOOD.replace("</body>", links + "</body>"), site / "index.html"), [])
            self.assertEqual(check_site_anchors.check('<a href="../">up</a>', site / "agent/index.html"), [])
            self.assertEqual(check_site_anchors.check('<a href="./zh/agent/">x</a>', site / "index.html"),
                             ["link ./zh/agent/ leads to no file of the site"])

    def test_leaked_list_marker(self):
        for marker in ("- <a id=\"x\"></a><strong>§4</strong>", "- <a id=\"x\"></a><strong>第四款</strong>"):
            with self.subTest(marker=marker):
                leaked = GOOD.replace("</ul>\n</body>", f"</ul>\n<p>Silence is not consent. {marker} Text.</p>\n</body>")
                self.assertEqual(len(check_site_anchors.check(leaked)), 1)



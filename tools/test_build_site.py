"""Tests for build_site and the site's Hugo templates.

build_site runs the token count, Hugo and the site check in that order
and stops at the first that fails, saying so when Hugo is missing. The
templates, built by Hugo from a made-up constitution, put the revision,
the length of the version for agents and the legend of the asterisk under
the title, and a popup that gives both versions' lengths; the tokens come
from data/lengths.json only when it counted the same text. The template
tests need hugo-0.167.0 and are skipped without it, except in CI.
"""

import contextlib
import hashlib
import html
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import tomllib
import unittest
from unittest import mock

import build_site
import constitution_render
import count_tokens

ROOT = Path(__file__).resolve().parent.parent
MARK = constitution_render.OMITTED_MARK
# Each file as build_constitution.py writes it: the header line, a blank
# line, the title, the text. The full version marks a part left out of
# the version for agents and gives its headings anchors.
FILES = {
  "en": (
    "Generated by `tools/build_constitution.py`.\n\n# Title\n\n"
    f'## <a id="one"></a>Article One{MARK}\n\nOne  two\tthree.\n'
  ),
  "en.agent": (
    "Generated by `tools/build_constitution.py`, for agents.\n\n# Title\n\n"
    "## Article One\n\nOne.\n"
  ),
  "zh": (
    "由 `tools/build_constitution.py` 生成。\n\n# 标题\n\n"
    '## <a id="one"></a>第一条\n\n不言即非同意。\n'
  ),
  "zh.agent": (
    "由 `tools/build_constitution.py` 生成。\n\n# 标题\n\n## 第一条\n\n不言。\n"
  ),
}
INDEX = 'status = "draft"\nrevision = "0.6"\nlanguages = ["en", "zh"]\n'


def visible(page: str) -> str:
  """Return the text of a page outside its scripts and styles, on one line.

  Args:
    page: The HTML page.

  Returns:
    The text.
  """
  page = re.sub(r"<(script|style)\b.*?</\1>", "", page, flags=re.S)
  return " ".join(html.unescape(re.sub(r"<[^>]*>", " ", page)).split())


class MainTest(unittest.TestCase):
  """main with the token count, Hugo and the site check mocked."""

  def main(self, count=0, run=None):
    stderr = io.StringIO()
    with (
      mock.patch("count_tokens.main", return_value=count) as counted,
      mock.patch("subprocess.run", **(run or {})) as hugo,
      mock.patch("check_site_anchors.main", return_value=0) as checked,
      contextlib.redirect_stderr(stderr),
    ):
      code = build_site.main(["--out", "/nonexistent-site", "--require-tokens"])
    return code, counted, hugo, checked, stderr.getvalue()

  def test_built_and_checked(self):
    code, counted, hugo, checked, _ = self.main(
      run={"return_value": mock.Mock(returncode=0)}
    )
    self.assertEqual(code, 0)
    counted.assert_called_once_with(["--require-tokens"])
    self.assertEqual(hugo.call_args.args[0][0], "hugo-0.167.0")
    checked.assert_called_once_with(["/nonexistent-site"])

  def test_stops_at_the_first_failure(self):
    code, _, hugo, checked, _ = self.main(count=1)
    self.assertEqual(code, 1)
    hugo.assert_not_called()
    code, _, _, checked, _ = self.main(
      run={"return_value": mock.Mock(returncode=255)}
    )
    self.assertEqual(code, 255)
    checked.assert_not_called()

  def test_no_hugo(self):
    code, _, _, checked, stderr = self.main(
      run={"side_effect": FileNotFoundError}
    )
    self.assertEqual(code, 2)
    self.assertIn("hugo-0.167.0 not found", stderr)
    checked.assert_not_called()

  def test_hugo_stalls(self):
    stalled = subprocess.TimeoutExpired("hugo-0.167.0", 120)
    code, _, _, checked, stderr = self.main(run={"side_effect": stalled})
    self.assertEqual(code, 1)
    self.assertIn("ran past", stderr)
    checked.assert_not_called()


# Skipped without Hugo, but never in CI (GitHub sets CI), which installs it.
@unittest.skipUnless(
  shutil.which(build_site.HUGO) or os.environ.get("CI"),
  f"needs {build_site.HUGO}",
)
class SiteTest(unittest.TestCase):
  """The site Hugo builds from web/ and the made-up constitution."""

  def build(
    self, lengths: dict[str, object] | None = None, raw: bool = False
  ) -> dict[str, str]:
    """Build the site in a temporary copy of the repo's layout.

    Args:
      lengths: The content of web/data/lengths.json, or None for no file.
      raw: Whether to return the pages' HTML instead of their text.

    Returns:
      The visible text of the four pages, or their HTML, by path.
    """
    with tempfile.TemporaryDirectory() as tmp:
      root = Path(tmp)
      shutil.copytree(
        ROOT / "web",
        root / "web",
        ignore=shutil.ignore_patterns("themes", "data", "resources"),
      )
      (root / "web/themes").mkdir()
      (root / "web/themes/hugo-book").symlink_to(ROOT / "web/themes/hugo-book")
      (root / "constitution").mkdir()
      (root / "constitution/index.toml").write_text(INDEX)
      for name, text in FILES.items():
        (root / f"constitution/constitution.{name}.md").write_text(text)
      if lengths is not None:
        (root / "web/data").mkdir()
        (root / "web/data/lengths.json").write_text(json.dumps(lengths))
      subprocess.run(
        [
          build_site.HUGO,
          "--source",
          str(root / "web"),
          "--destination",
          str(root / "site"),
          "--panicOnWarning",
          "--quiet",
        ],
        check=True,
        timeout=build_site.HUGO_TIMEOUT,
      )
      pages = {
        page: (root / "site" / page).read_text(encoding="utf-8")
        for page in (
          "index.html",
          "agent/index.html",
          "zh/index.html",
          "zh/agent/index.html",
        )
      }
      return pages if raw else {p: visible(t) for p, t in pages.items()}

  @staticmethod
  def length(name: str) -> tuple[int, int, str]:
    """Return the length of a made-up file as the site gives it.

    Args:
      name: The file's key in FILES.

    Returns:
      Its characters, its words and its SHA-256.
    """
    text = count_tokens.counted(FILES[name])
    sha = hashlib.sha256(text.encode()).hexdigest()
    return len(text), len(text.split()), sha

  def test_lengths_without_tokens(self):
    pages = self.build()
    chars, words, _ = self.length("en.agent")
    full_chars, full_words, _ = self.length("en")
    self.assertIn(
      f"Revision 0.6 (draft) {chars} characters · {words} words · tokens"
      " not counted",
      pages["index.html"],
    )
    self.assertIn(
      f"Agent version {chars} {words} — Full version, this page"
      f" {full_chars} {full_words} —",
      pages["index.html"],
    )
    self.assertIn("so they were not counted.", pages["index.html"])
    self.assertIn("Counted at revision 0.6.", pages["index.html"])
    zh_chars, _, _ = self.length("zh.agent")
    self.assertIn(
      f"修订号 0.6 (草案) {zh_chars} 字符 · token 数未计算",
      pages["zh/index.html"],
    )
    self.assertIn("字符 token agent 版", pages["zh/index.html"])

  def test_legend_only_when_marked(self):
    pages = self.build()
    self.assertIn("* Background for people:", pages["index.html"])
    self.assertNotIn("写给人看的背景：本宪法", pages["zh/index.html"])

  def test_agent_page(self):
    pages = self.build()
    self.assertIn(
      "Title Revision 0.6 (draft) Back to the full version Article One One.",
      pages["agent/index.html"],
    )
    self.assertIn(
      "修订号 0.6 (草案) 回到完整版 第一条 不言。", pages["zh/agent/index.html"]
    )

  def test_title(self):
    """The title breaks only before the parenthesis and has no `#` link."""
    titles = {"en": "Title (2026-10 Edition)", "zh": "标题 (2026-10 版)"}
    files = {
      name: text.replace("\n# Title\n", f"\n# {titles['en']}\n").replace(
        "\n# 标题\n", f"\n# {titles['zh']}\n"
      )
      for name, text in FILES.items()
    }
    with mock.patch.dict(FILES, files):
      pages = self.build(raw=True)
    for page, (name, edition) in {
      "index.html": ("Title", "(2026-10 Edition)"),
      "agent/index.html": ("Title", "(2026-10 Edition)"),
      "zh/index.html": ("标题", "(2026-10 版)"),
      "zh/agent/index.html": ("标题", "(2026-10 版)"),
    }.items():
      with self.subTest(page=page):
        h1 = re.search(r"<h1\b[^>]*>(.*?)</h1>", pages[page], re.S)
        assert h1 is not None
        self.assertEqual(
          h1.group(1).strip(),
          f'<span class="nobreak">{name}</span>'
          f' <span class="nobreak">{edition}</span>',
        )

  def test_tokens_from_lengths_json(self):
    counts = {
      (lang, version): {
        "sha256": self.length(f"{lang}{suffix}")[2],
        "tokens": tokens + (version == "agent"),
      }
      for lang, tokens in (("en", 1200), ("zh", 3400))
      for version, suffix in (("full", ""), ("agent", ".agent"))
    }
    # A count of another text than the one built is not shown.
    counts["zh", "agent"]["sha256"] = "0" * 64
    pages = self.build(
      {
        "commit": "abc1234",
        **{
          lang: {v: counts[lang, v] for v in ("full", "agent")}
          for lang in ("en", "zh")
        },
      }
    )
    self.assertIn("words · 1,201 tokens", pages["index.html"])
    chars, words, _ = self.length("en")
    self.assertIn(f"this page {chars} {words} 1,200", pages["index.html"])
    self.assertIn("Tokens counted by Anthropic", pages["index.html"])
    self.assertIn(
      "Counted at revision 0.6, commit abc1234.", pages["index.html"]
    )
    self.assertIn("token 数未计算", pages["zh/index.html"])
    self.assertIn("所以没有算。", pages["zh/index.html"])
    self.assertIn("按修订号 0.6 计算。", pages["zh/index.html"])


class OmittedMarkTest(unittest.TestCase):
  def test_site_knows_the_mark(self):
    """web/hugo.toml finds the asterisk as the build writes it."""
    with (ROOT / "web/hugo.toml").open("rb") as f:
      params = tomllib.load(f)["params"]
    self.assertEqual(params["omittedMark"], MARK)


if __name__ == "__main__":
  unittest.main()
